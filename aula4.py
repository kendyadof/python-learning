# Tipos int e float
# int -> número inteiro
# o tipo int representa qualquer número positivo ou negativo. int sem sinal é considerado positivo.
# print(11) #  int
# print(0) # int
# print(-11) # int

# float -> número com ponto flutuante, o tipo float representa qualquer número positivo ou negativo com ponto flutuante. Float sem sinal é considerado positivo.
# print(1.1, 10.11) # SEMPRE separa o ponto pra casa decimal
# print(0.0,-1.5)


# a função type mostra o tipo que o python inferiu ao valor.
print(type('Otávio')) # type é uma CLASSE, apesar de começar com letra minúscula
print(type(0)) 
print(type(1.1), type(-1.1),type(0.0)) 
